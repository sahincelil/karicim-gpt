export const pluginCategories = [...new Set(pluginCatalog.map(item => item.category))].sort();

export function searchPlugins({ q = '', category = '' } = {}) {
  const term = String(q).trim().toLocaleLowerCase('tr-TR');
  return pluginCatalog.filter(item => {
    const haystack = `${item.name} ${item.key} ${item.category} ${item.id}`.toLocaleLowerCase('tr-TR');
    return (!term || haystack.includes(term)) && (!category || item.category === category);
  });
}
